#!/usr/bin/env node
// Generates supabase/migrations/0006_quiz_questions_seed.sql from the
// category-split question modules in ./questions/. Idempotent via
// quiz_questions.source_key — re-running the migration is a no-op.
//
// Usage: npm run seed:quiz
//
// Quality bar enforced here:
//  - source_key globally unique
//  - choices is a string[] of length 2-6
//  - correct_index in range [0, choices.length)
//  - category ∈ CATEGORIES from lib/glossary/categories.ts
//  - difficulty ∈ DIFFICULTIES
//  - prompt and explanation are non-empty
// The build aborts on any violation.

import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { allQuestions } from "./questions/index.mjs";

const __dirname = dirname(fileURLToPath(import.meta.url));
const repoRoot = resolve(__dirname, "..", "..");
const outPath = join(
  repoRoot,
  "supabase",
  "migrations",
  "0006_quiz_questions_seed.sql",
);

const CATEGORIES = new Set([
  "Investing basics",
  "Stocks & equities",
  "Bonds & fixed income",
  "Market structure & order types",
  "Financial statements",
  "Ratios & valuation",
  "Macro & monetary policy",
  "Options & derivatives",
  "ETFs & funds",
  "Technical analysis",
  "Corporate actions",
  "Crypto",
  "Behavioral finance",
  "Taxes & retirement",
  "Risk & portfolio management",
]);

const DIFFICULTIES = new Set(["Basic", "Beginner", "Intermediate", "Advanced"]);

function sqlStr(value) {
  // Single-quote string literal with doubled internal quotes.
  return `'${String(value).replace(/'/g, "''")}'`;
}

function validate(questions) {
  const seenKeys = new Set();
  const issues = [];
  questions.forEach((q, i) => {
    const ctx = `[${i}] ${q.source_key ?? "<no-key>"}`;
    if (!q.source_key || typeof q.source_key !== "string") {
      issues.push(`${ctx}: missing source_key`);
    } else if (seenKeys.has(q.source_key)) {
      issues.push(`${ctx}: duplicate source_key`);
    } else {
      seenKeys.add(q.source_key);
    }
    if (!q.prompt || typeof q.prompt !== "string") {
      issues.push(`${ctx}: missing prompt`);
    }
    if (!Array.isArray(q.choices) || q.choices.length < 2 || q.choices.length > 6) {
      issues.push(`${ctx}: choices must be a 2-6 string array`);
    } else if (q.choices.some((c) => typeof c !== "string" || !c.trim())) {
      issues.push(`${ctx}: every choice must be a non-empty string`);
    }
    if (
      !Number.isInteger(q.correct_index) ||
      q.correct_index < 0 ||
      (Array.isArray(q.choices) && q.correct_index >= q.choices.length)
    ) {
      issues.push(`${ctx}: correct_index out of range`);
    }
    if (!q.explanation || typeof q.explanation !== "string") {
      issues.push(`${ctx}: missing explanation`);
    }
    if (!CATEGORIES.has(q.category)) {
      issues.push(`${ctx}: unknown category ${q.category}`);
    }
    if (!DIFFICULTIES.has(q.difficulty)) {
      issues.push(`${ctx}: unknown difficulty ${q.difficulty}`);
    }
    if (q.glossary_slug !== undefined && q.glossary_slug !== null) {
      if (typeof q.glossary_slug !== "string" || !q.glossary_slug.trim()) {
        issues.push(`${ctx}: glossary_slug must be a non-empty string or null`);
      }
    }
  });
  return issues;
}

function emitSql(questions) {
  const lines = [];
  lines.push(
    "-- Daily Quiz question pool seed — auto-generated by scripts/seed-quiz/build-migration.mjs.",
    "-- Do not edit this file directly. Re-run `npm run seed:quiz` after changing the question",
    "-- source modules under scripts/seed-quiz/questions/.",
    "-- Idempotent via source_key (unique). Re-running the migration is a no-op.",
    "",
  );

  // Chunk into batches to keep individual statements manageable.
  const BATCH = 100;
  for (let i = 0; i < questions.length; i += BATCH) {
    const batch = questions.slice(i, i + BATCH);
    lines.push(
      "insert into public.quiz_questions",
      "  (source_key, prompt, choices, correct_index, explanation, category, difficulty, glossary_slug)",
      "values",
    );
    const values = batch.map((q, j) => {
      const tuple = [
        sqlStr(q.source_key),
        sqlStr(q.prompt),
        `${sqlStr(JSON.stringify(q.choices))}::jsonb`,
        String(q.correct_index),
        sqlStr(q.explanation),
        sqlStr(q.category),
        sqlStr(q.difficulty),
        q.glossary_slug ? sqlStr(q.glossary_slug) : "null",
      ].join(", ");
      const trailing = j === batch.length - 1 ? "" : ",";
      return `  (${tuple})${trailing}`;
    });
    lines.push(...values);
    lines.push("on conflict (source_key) do nothing;", "");
  }

  return lines.join("\n");
}

function main() {
  const questions = allQuestions();
  const issues = validate(questions);
  if (issues.length > 0) {
    console.error(`Seed validation failed (${issues.length} issues):`);
    issues.slice(0, 20).forEach((line) => console.error(`  ${line}`));
    if (issues.length > 20) console.error(`  …and ${issues.length - 20} more`);
    process.exit(1);
  }
  const sql = emitSql(questions);
  mkdirSync(dirname(outPath), { recursive: true });
  writeFileSync(outPath, sql, "utf8");
  console.log(
    `Wrote ${questions.length} questions → ${outPath.replace(repoRoot + "\\", "").replace(repoRoot + "/", "")}`,
  );
}

main();
